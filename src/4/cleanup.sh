#!/bin/bash
# копируй строки по одной, разбираясь, что делает каждая.

echo "Снимаем замок с амбара..."
sudo chattr -i ~/backups

# ls -t ~/backups - выводит файлы в папке backups, отсортированные
#                   по времени изменения (новые сверху, старые снизу).
# tail -n 1       - берет последнюю строку из этого списка,
#                   то есть самый старый бэкап.
OLDEST=$(ls -t ~/backups | tail -n 1)

rm ~/backups/"$OLDEST"
echo "Удалили старый бэкап: $OLDEST"

echo "Закрываем замок обратно..."
sudo chattr +i ~/backups
