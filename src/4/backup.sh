#!/usr/bin/env bash
# если запутался в шагах - копируй строки по одной, разбираясь, что делает каждая.

# снимаем замок с амбара (chattr -i), если папка backups уже защищена
# с прошлого запуска. В первый раз, пока замка еще нет, эта строка
# просто ничего не сломает.
sudo chattr -i ~/backups

# DATE - переменная с текущей датой и временем, нужна, чтобы каждый
# бэкап имел уникальное имя и не перезаписывал предыдущий.
DATE=$(date +%Y-%m-%d_%H-%M)

echo "Начинаю упаковку сайта..."

# tar -czvf <куда_сохранить> <что_архивировать>
#   c - создать архив
#   z - сжать (gzip)
#   v - показывать процесс архивирования, перечисляет файлы (verbose)
#   f - в файл с указанным именем
tar -czvf ~/backups/site_$DATE.tar.gz /var/www/demo/

echo "Бэкап успешно сохранен!"

# закрываем замок обратно - защищаем папку backups от случайного rm -rf.
sudo chattr +i ~/backups
